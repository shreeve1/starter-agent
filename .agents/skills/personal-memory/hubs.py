#!/usr/bin/env python3
"""Generate Client Memory hubs: memory/<client_folder>/_hubs/<short>.md (client_folder from memory/schema.json, default clients).

Deterministic and idempotent: output depends only on the notes on disk.
--check writes nothing and exits 1 if any hub would be created, changed or removed.
"""

import argparse
import re
import sys
from pathlib import Path
from urllib.parse import quote

sys.path.insert(0, str(Path(__file__).resolve().parent))
import schema

HUB_DIR = "_hubs"
INDEX = "index.md"  # generated list of every hub; never a hub itself


def client_root(memory_dir):
    """memory/<client_folder>/, the folder that holds Client Memory notes and hubs."""
    return Path(memory_dir) / schema.load(memory_dir)["client_folder"]


def read_note(path):
    """Note text that never raises on encoding: BOM stripped, CRLF to LF, bad bytes replaced."""
    return (
        path.read_bytes().decode("utf-8", errors="replace").lstrip("\ufeff").replace("\r\n", "\n")
    )


def parse_frontmatter(path):
    text = read_note(path)
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end == -1:
        return {}
    fields = {}
    for line in text[4:end].splitlines():
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if not m:
            continue
        value = m.group(2).strip()
        if value and value[:1] in "\"'":
            q = value[0]
            close = value.find(q, 1)
            value = value[1:close] if close != -1 else value[1:]
        else:
            value = re.split(r"\s+#", value, maxsplit=1)[0].strip()
        fields[m.group(1)] = value
    return fields


def note_paths(memory_dir):
    root = client_root(memory_dir)
    if not root.is_dir():
        return []
    return sorted(p for p in root.rglob("*.md") if p.relative_to(root).parts[0] != HUB_DIR)


def collect(memory_dir):
    """Map client short -> subject -> [(title, verified, vault path)] using folder layout."""
    root = client_root(memory_dir)
    clients = {}
    for p in note_paths(memory_dir):
        parts = p.relative_to(root).parts
        if len(parts) != 3:
            continue
        subject, short, _ = parts
        fm = parse_frontmatter(p)
        title = fm.get("title") or p.stem
        verified = fm.get("verified") or "unknown"
        rel = "memory/" + p.relative_to(memory_dir).as_posix()
        clients.setdefault(short, {}).setdefault(subject, []).append((title, verified, rel))
    return clients


def within_entity(path, vault_root, folder, short):
    try:
        entity_path = vault_root / folder / short
        entity = entity_path.resolve()
        return (
            not (vault_root / folder).is_symlink()
            and not entity_path.is_symlink()
            and entity.is_relative_to(vault_root.resolve())
            and path.resolve().is_relative_to(entity)
        )
    except (OSError, RuntimeError):
        return False


def doc_links(vault_root, folder, short, kind):
    d = vault_root / folder / short / kind
    if not within_entity(d, vault_root, folder, short) or not d.is_dir():
        return []
    return sorted(
        p.relative_to(vault_root).as_posix()
        for p in d.rglob("*.md")
        if within_entity(p, vault_root, folder, short) and p.is_file()
    )


def label(text):
    """Backslash-escape the characters that end or break a Markdown link label."""
    return re.sub(r"([\\\[\]])", r"\\\1", text)


def procedure_clients(vault_root, folder):
    """Client shorts whose folder holds Procedures (<folder>/<short>/procedures/**/*.md)."""
    base = vault_root / folder
    if not base.is_dir():
        return []
    return sorted(
        d.name
        for d in base.iterdir()
        if d.is_dir() and d.name != HUB_DIR and doc_links(vault_root, folder, d.name, "procedures")
    )


def glossary_names(memory_dir):
    """{short: client name} from memory/glossary.md: the last cell's text before its first ':' or ';'."""
    path = memory_dir / "glossary.md"
    if not path.is_file():
        return {}
    names = {}
    for line in read_note(path).splitlines():
        if not line.lstrip().startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        short = cells[0].strip("`")
        name = re.split(r"[:;]", cells[-1], maxsplit=1)[0].strip()
        if len(cells) > 1 and short and name and short not in names:
            names[short] = name
    return names


def render_index(shorts, memory_dir, folder):
    names = glossary_names(memory_dir)
    lines = [
        "---",
        "type: client-hub-index",
        "generated: hubs.py",
        "---",
        "",
        "# Client hubs",
        "",
        "Generated by the `personal-memory` skill (`hubs.py`). Do not edit by hand.",
        "",
    ]
    for short in shorts:
        link = f"- [{short}](memory/{folder}/{HUB_DIR}/{short}.md)"
        lines.append(f"{link} {names[short]}" if short in names else link)
    return "\n".join(lines).rstrip("\n") + "\n"


def render(short, subjects, vault_root, subject_order, folder, document_dirs):
    lines = [
        "---",
        "type: client-hub",
        f"client: {short}",
        "generated: hubs.py",
        "---",
        "",
        f"# {short} client hub",
        "",
        "Generated by the `personal-memory` skill (`hubs.py`). Do not edit by hand.",
        "",
    ]
    readme = vault_root / folder / short / "README.md"
    if within_entity(readme, vault_root, folder, short) and readme.is_file():
        lines.extend([f"- [README]({quote(readme.relative_to(vault_root).as_posix())})", ""])
    ordered = [s for s in subject_order if s in subjects] + sorted(
        s for s in subjects if s not in subject_order
    )
    for subject in ordered:
        lines.append(f"## {subject}")
        lines.append("")
        for title, verified, rel in sorted(subjects[subject], key=lambda n: n[2]):
            lines.append(f"- [{title}]({rel}) (verified {verified})")
        lines.append("")
    for kind in document_dirs:
        links = doc_links(vault_root, folder, short, kind)
        if links:
            lines.append(f"## {kind}")
            lines.append("")
            lines.extend(f"- [{label(Path(link).stem)}]({quote(link)})" for link in links)
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def plan(memory_dir):
    """Return (wanted {path: text}, stale [paths]) for the hub directory."""
    memory_dir = Path(memory_dir)
    vault_root = memory_dir.resolve().parent
    data = schema.load(memory_dir)
    subject_order = data["client_subjects"]
    folder = data["client_folder"]
    hub_dir = memory_dir / folder / HUB_DIR
    clients = collect(memory_dir)
    # A client with Procedures but no Client Memory notes still gets a hub, so its Procedures are listed.
    for short in procedure_clients(vault_root, folder):
        clients.setdefault(short, {})
    wanted = {
        hub_dir / f"{short}.md": render(
            short, subjects, vault_root, subject_order, folder, data["client_dirs"]
        )
        for short, subjects in sorted(clients.items())
    }
    index = hub_dir / INDEX
    if wanted:
        wanted[index] = render_index(sorted(clients), memory_dir, folder)
    existing = sorted(hub_dir.glob("*.md")) if hub_dir.is_dir() else []
    stale = [p for p in existing if p not in wanted and p != index]
    if (
        index.exists()
        and index not in wanted
        and parse_frontmatter(index).get("generated") == "hubs.py"
    ):
        stale.append(index)
    return wanted, stale


def comparable(text: str) -> str:
    return "".join(
        line for line in text.splitlines(keepends=True) if not line.startswith("Generated by ")
    )


def drift(memory_dir):
    """List hub paths that would be written or removed."""
    wanted, stale = plan(memory_dir)
    changed = [
        p
        for p, text in wanted.items()
        if not p.exists() or comparable(read_note(p)) != comparable(text)
    ]
    return changed, stale


def main():
    ap = argparse.ArgumentParser(description="Generate Client Memory hubs.")
    ap.add_argument("--memory", default="memory", help="Memory directory root (default: memory)")
    ap.add_argument(
        "--check", action="store_true", help="Exit 1 if any hub would change; write nothing"
    )
    args = ap.parse_args()
    memory_dir = Path(args.memory)
    changed, stale = drift(memory_dir)
    if args.check:
        if changed or stale:
            print(
                f"Hubs out of date: changed={[str(p) for p in changed]} "
                f"stale={[str(p) for p in stale]}"
            )
            sys.exit(1)
        print("Hubs up to date.")
        return
    wanted, _ = plan(memory_dir)
    changed = [p for p, text in wanted.items() if not p.exists() or read_note(p) != text]
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(wanted[p], encoding="utf-8")
        print(f"wrote {p}")
    for p in stale:
        p.unlink()
        print(f"removed {p}")
    if not changed and not stale:
        print("Hubs up to date.")


if __name__ == "__main__":
    main()
