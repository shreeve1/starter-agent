#!/usr/bin/env python3
"""Generate topic indexes for the topic-ized memory folders.

Builds `memory/workflows/index.md` and `memory/decisions/index.md` from the
promoted files on disk, reading each file's frontmatter (title, summary,
status, updated) as the single source for its index line. A `status: superseded`
file is listed like any other; `gate.py audit` warns that it should be deleted.

When the topic index would exceed INDEX_LIMIT, it is split: the topic dir's
index.md lists one line per topic, and each topic gets its own index.md under
memory/<topic_dir>/<topic>/. Generated per-topic indexes are removed again once
the index fits. A hand-written index.md is never overwritten or removed.

Deterministic and idempotent: output depends only on the files on disk.
`--check` writes nothing and exits 1 if any index would be created, changed or
removed, or if a hand-written index blocks a split.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hubs  # noqa: E402
import schema  # noqa: E402

DISPLAY = {"workflows": "Workflow", "decisions": "Decision"}
INDEX_LIMIT = 10240  # gate.py warns above this; a topic dir index over it is split per topic


def is_entry(path):
    """Promoted notes only: generated indexes and *.runs.md run logs are not listed."""
    return path.name != "index.md" and not path.name.endswith(".runs.md")


def promoted_files(memory_dir, topic_dir):
    """Sorted [Path] of promoted .md files under memory/<topic_dir>/<topic>/."""
    base = memory_dir / topic_dir
    topics = schema.load(memory_dir)["topics"]
    out = []
    for topic in topics:
        tdir = base / topic
        if tdir.is_dir():
            out.extend(p for p in sorted(tdir.glob("*.md")) if is_entry(p))
    return out


def parse_file(path, memory_dir):
    """(title, summary, status, updated, workspace-relative path) from frontmatter."""
    fm = hubs.parse_frontmatter(path)
    rel = "memory/" + path.relative_to(memory_dir).as_posix()
    return (
        fm.get("title") or path.stem,
        fm.get("summary", ""),
        fm.get("status") or "promoted",
        fm.get("updated", ""),
        rel,
    )


def entries(memory_dir, topic_dir):
    """{topic: [index line]} for topics that have promoted notes, in schema order."""
    topics = schema.load(memory_dir)["topics"]
    grouped = {topic: [] for topic in topics}
    for p in promoted_files(memory_dir, topic_dir):
        title, summary, _status, updated, rel = parse_file(p, memory_dir)
        grouped[p.parent.name].append(f"- [{title}]({rel}) {summary} ({updated})".rstrip())
    return {topic: rows for topic, rows in grouped.items() if rows}


def header(topic_dir, suffix=""):
    return [
        "---",
        "type: memory-index",
        "generated: indexes.py",
        "---",
        "",
        f"# {DISPLAY[topic_dir]} Index{suffix}",
        "",
        "Generated by the `personal-memory` skill (`indexes.py`). Do not edit by hand.",
        "",
    ]


def finish(lines):
    return "\n".join(lines).rstrip("\n") + "\n"


def render_single(topic_dir, grouped):
    lines = header(topic_dir)
    for topic, rows in grouped.items():
        lines += [f"## {topic}", "", *rows, ""]
    return finish(lines)


def render_split(topic_dir, grouped):
    lines = header(topic_dir)
    for topic, rows in grouped.items():
        count = f"{len(rows)} entr{'y' if len(rows) == 1 else 'ies'}"
        lines.append(f"- [{topic}](memory/{topic_dir}/{topic}/index.md) {count}")
    lines.append("")
    return finish(lines)


def render_topic(topic_dir, topic, rows):
    return finish(header(topic_dir, f": {topic}") + [*rows, ""])


def generated(path):
    return hubs.parse_frontmatter(path).get("generated") == "indexes.py"


def plan(memory_dir):
    """(wanted {path: text}, stale, blocked, kept) for every topic dir.

    stale: generated per-topic indexes no longer needed (removed on write).
    blocked: a hand-written index sits where a split index must go (nothing is written).
    kept: hand-written per-topic indexes, left alone.
    """
    data = schema.load(memory_dir)
    wanted, stale, blocked, kept = {}, [], [], []
    for topic_dir in data["topic_dirs"]:
        base = memory_dir / topic_dir
        grouped = entries(memory_dir, topic_dir)
        single = render_single(topic_dir, grouped)
        pages = {}
        if len(single.encode("utf-8")) <= INDEX_LIMIT:
            wanted[base / "index.md"] = single
        else:
            wanted[base / "index.md"] = render_split(topic_dir, grouped)
            pages = {t: render_topic(topic_dir, t, rows) for t, rows in grouped.items()}
        for topic in data["topics"]:
            page = base / topic / "index.md"
            if topic in pages:
                if page.exists() and not generated(page):
                    blocked.append(page)
                else:
                    wanted[page] = pages[topic]
            elif page.exists():
                (stale if generated(page) else kept).append(page)
    return wanted, stale, blocked, kept


def unwritten(wanted):
    """Paths whose on-disk text differs from the plan (generated line ignored)."""
    return [
        p
        for p, text in wanted.items()
        if not p.exists() or hubs.comparable(hubs.read_note(p)) != hubs.comparable(text)
    ]


def drift(memory_dir):
    """([paths] to write or blocked, [stale paths] to remove)."""
    wanted, stale, blocked, _ = plan(memory_dir)
    return unwritten(wanted) + blocked, stale


def main():
    ap = argparse.ArgumentParser(description="Generate topic indexes for workflows/decisions.")
    ap.add_argument("--memory", default="memory", help="Memory directory root (default: memory)")
    ap.add_argument(
        "--check", action="store_true", help="Exit 1 if any index would change; write nothing"
    )
    args = ap.parse_args()
    memory_dir = Path(args.memory)
    wanted, stale, blocked, kept = plan(memory_dir)
    if args.check:
        changed = unwritten(wanted) + blocked + stale
        if changed:
            print("Indexes out of date: %s (run indexes.py)" % [str(p) for p in changed])
            sys.exit(1)
        print("Indexes up to date.")
        return
    if blocked:
        print(
            "Nothing written: a hand-written index is in the way of a split: %s"
            % [str(p) for p in blocked]
        )
        sys.exit(1)
    for p in kept:
        print(f"kept (not generated by indexes.py): {p}")
    changed = [p for p, text in wanted.items() if not p.exists() or hubs.read_note(p) != text]
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(wanted[p], encoding="utf-8")
        print(f"wrote {p}")
    for p in stale:
        p.unlink()
        print(f"removed {p}")
    if not changed and not stale:
        print("Indexes up to date.")


if __name__ == "__main__":
    main()
